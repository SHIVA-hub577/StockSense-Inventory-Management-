/**
 * Serialise data for a <script type="application/json"> block without allowing
 * "</script>" (or similar) inside user data to break out of the tag.
 */
const jsonForScript = (data) =>
  JSON.stringify(data)
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');

/**
 * Build a query string from current filters with overrides; empty values are dropped.
 * e.g. buildQuery({ status: 'low', page: 2 }, { page: 3 }) -> "?status=low&page=3"
 */
const buildQuery = (current = {}, overrides = {}) => {
  const params = new URLSearchParams();
  const merged = { ...current, ...overrides };
  for (const [key, value] of Object.entries(merged)) {
    if (value !== undefined && value !== null && value !== '' && value !== false) {
      params.set(key, value);
    }
  }
  const qs = params.toString();
  return qs ? `?${qs}` : '';
};

