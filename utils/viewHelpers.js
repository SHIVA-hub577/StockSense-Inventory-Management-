// ₹ amounts (whole rupees above 1,000)
const fmtMoney = (value) => {
  const n = Number(value) || 0;
  return n.toLocaleString('en-IN', { style: 'currency', currency: 'INR', maximumFractionDigits: Math.abs(n) >= 1000 ? 0 : 2 });
};

// "in 5 days", "today", "3 days ago"
const fmtRelativeDays = (value) => {
  if (!value) return '—';
  const start = new Date();
  start.setHours(0, 0, 0, 0);
  const d = new Date(value);
  d.setHours(0, 0, 0, 0);
  const diff = Math.round((d - start) / 86400000);
  if (diff === 0) return 'today';
  if (diff === 1) return 'tomorrow';
  if (diff === -1) return 'yesterday';
  return diff > 0 ? `in ${diff} days` : `${-diff} days ago`;
};

// "5 min ago" for the activity feed
const fmtAgo = (value) => {
  const seconds = Math.max(0, Math.round((Date.now() - new Date(value).getTime()) / 1000));
  if (seconds < 60) return 'just now';
  if (seconds < 3600) return `${Math.floor(seconds / 60)} min ago`;
  if (seconds < 86400) return `${Math.floor(seconds / 3600)} h ago`;
  return `${Math.floor(seconds / 86400)} d ago`;
};

const fmtQty = (value) => {
  const n = Number(value) || 0;
  return n.toLocaleString('en-IN', { maximumFractionDigits: 3 });
};

const fmtDate = (value) => {
  if (!value) return '—';
  return new Date(value).toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' });
};

const fmtDateTime = (value) => {
  if (!value) return '—';
  return new Date(value).toLocaleString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  });
};

// YYYY-MM-DD in server local time, for <input type="date">
const toDateInput = (value) => {
  const d = value ? new Date(value) : new Date();
  const pad = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
};

const startOfToday = () => {
  const d = new Date();
  d.setHours(0, 0, 0, 0);
  return d;
};

// Open operation scheduled before today
